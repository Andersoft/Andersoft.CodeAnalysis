using Microsoft.CodeAnalysis;
using Xunit;

namespace Andersoft.CodeAnalysis.Tests;

public sealed class MessageHandlerInjectionAnalyzerTests
{
    private const string Contracts = """
        namespace Andersoft.Messaging.Abstractions
        {
            public interface IMessageHandler<in TMessage> { }
            public interface IMessageHandler<in TMessage, TResult> { }
            public sealed class TypedDispatcher { }
        }
        namespace Example
        {
            public sealed class Message { }
            public class Handler : Andersoft.Messaging.Abstractions.IMessageHandler<Message, string> { }
            public sealed class DerivedHandler : Handler { }
            public interface ISpecialHandler : Andersoft.Messaging.Abstractions.IMessageHandler<Message, string> { }
        }
        """;

    [Theory]
    [InlineData("Andersoft.Messaging.Abstractions.IMessageHandler<Message, string>")]
    [InlineData("Andersoft.Messaging.Abstractions.IMessageHandler<Message>")]
    [InlineData("Handler")]
    [InlineData("DerivedHandler")]
    [InlineData("ISpecialHandler")]
    [InlineData("System.Collections.Generic.IEnumerable<Handler>")]
    [InlineData("Andersoft.Messaging.Abstractions.IMessageHandler<Message, string>[]")]
    [InlineData("System.Lazy<Handler>")]
    [InlineData("System.Func<Andersoft.Messaging.Abstractions.IMessageHandler<Message, string>>")]
    public async Task PrimaryConstructorHandlerDependenciesAreErrors(string dependencyType)
    {
        var source = Contracts + $$"""
            namespace Example
            {
                public sealed class Consumer({{dependencyType}} dependency) { }
            }
            """;

        var diagnostic = Assert.Single(await AnalyzerTestHarness.AnalyzeAsync(source, new Rap064Analyzer()));

        Assert.Equal("RAP064", diagnostic.Id);
        Assert.Equal(DiagnosticSeverity.Error, diagnostic.Severity);
        Assert.Equal("dependency", source.Substring(diagnostic.Location.SourceSpan.Start, diagnostic.Location.SourceSpan.Length));
    }

    [Theory]
    [InlineData("public Consumer(Handler dependency) { }")]
    [InlineData("public void Execute(Handler dependency) { }")]
    [InlineData("public Handler Dependency { get; set; }")]
    [InlineData("private Handler dependency;")]
    public async Task ConstructorMethodPropertyAndFieldDependenciesAreFlagged(string member)
    {
        var source = Contracts + $$"""
            namespace Example
            {
                public sealed class Consumer { {{member}} }
            }
            """;

        Assert.Single(await AnalyzerTestHarness.AnalyzeAsync(source, new Rap064Analyzer()));
    }

    [Theory]
    [InlineData("public sealed record Consumer(Handler Dependency);")]
    [InlineData("public sealed class Consumer<T>(T dependency) where T : ISpecialHandler { }")]
    [InlineData("public sealed class Consumer(AliasedHandler dependency) : Andersoft.Messaging.Abstractions.IMessageHandler<Message, string> { }")]
    public async Task RecordsConstraintsAliasesAndHandlerConsumersAreFlagged(string declaration)
    {
        var source = Contracts + $$"""
            namespace Example
            {
                using AliasedHandler = Andersoft.Messaging.Abstractions.IMessageHandler<Message, string>;
                {{declaration}}
            }
            """;

        Assert.Single(await AnalyzerTestHarness.AnalyzeAsync(source, new Rap064Analyzer()));
    }

    [Fact]
    public async Task DispatchersHandlerImplementationsAndUnrelatedTypesAreAllowed()
    {
        var source = Contracts + """
            namespace Example
            {
                public interface IMessageHandler<TMessage, TResult> { }
                public sealed class LooksLikeHandler { }
                public sealed class Consumer(Andersoft.Messaging.Abstractions.TypedDispatcher dispatcher,
                    IMessageHandler<Message, string> unrelated, LooksLikeHandler service) { }
                public sealed class GenericConsumer<T>(T value) where T : System.IComparable<T> { }
            }
            """;

        Assert.Empty(await AnalyzerTestHarness.AnalyzeAsync(source, new Rap064Analyzer()));
    }

    [Fact]
    public async Task GeneratedDispatcherDependenciesAreIgnored()
    {
        var source = "// <auto-generated/>\n" + Contracts + """
            namespace Example
            {
                public sealed class GeneratedDispatcher(Handler handler) { }
            }
            """;

        Assert.Empty(await AnalyzerTestHarness.AnalyzeAsync(source, new Rap064Analyzer()));
    }
}
